#!/usr/bin/env bash
# Regenerates tasks/INDEX.md from the task files.
# Usage: bash ~/.claude/agents/pocket-it/bin/tasks-index.sh [tasks-dir]
# Tolerates both header forms (**Key**: value and **Key:** value) and missing fields.
set -uo pipefail
DIR="${1:-tasks}"
if [[ ! -d "$DIR" ]]; then
  # fall back to the repo root (agents may run from a subdirectory or a worktree)
  ROOT=$(git rev-parse --show-toplevel 2>/dev/null || true)
  [[ -n "$ROOT" && -d "$ROOT/tasks" ]] && DIR="$ROOT/tasks"
fi
[[ -d "$DIR" ]] || { echo "tasks-index: no tasks/ directory found (cwd: $(pwd))" >&2; exit 1; }

field() { # field <file> <name> — first match of **Name**: or **Name:**, case-insensitive, empty if absent
  grep -m1 -iE "^\*\*$2(\*\*:|:\*\*)" "$1" 2>/dev/null | sed -E "s/^\*\*[^*:]+(\*\*:|:\*\*)[[:space:]]*//; s/[[:space:]]+$//" || true
}

files=$(ls "$DIR"/*.md 2>/dev/null | grep -v '/INDEX\.md$' | sort -V)
count=$(printf '%s\n' "$files" | grep -c . || true)

{
  echo "# Task board"
  echo
  echo "Generated by tasks-index.sh — do not edit by hand. $count tasks."
  echo
  echo "| ID | Title | Label | Status | Depends on | PR |"
  echo "|---|---|---|---|---|---|"
  for f in $files; do
    t=$(head -1 "$f" | sed -E 's/^#+[[:space:]]*//')
    id=$(printf '%s' "$t" | sed -E 's/[[:space:]]*(—|–|:|-)[[:space:]].*$//')
    name=$(printf '%s' "$t" | sed -E 's/^[^[:space:]]+[[:space:]]*(—|–|:|-)[[:space:]]*//')
    [[ "$name" == "$t" ]] && name=""
    st=$(field "$f" Status);      st="${st:-Todo}"
    lb=$(field "$f" Label)
    dep=$(field "$f" "Depends on"); [[ -z "$dep" ]] && dep=$(field "$f" "Depends On"); [[ -z "$dep" ]] && dep=$(field "$f" "Blocked by")
    pr=$(field "$f" PR)
    [[ "$pr" =~ ^https?:// ]] && pr="[#${pr##*/}]($pr)"
    echo "| $id | ${name:-$t} | ${lb:--} | $st | ${dep:-none} | ${pr:--} |"
  done
  echo
  echo "## Summary"
  for s in "To ?Do|Todo" "In Progress" "Needs Work" "Done"; do
    n=0
    for f in $files; do grep -qiE "^\*\*Status(\*\*:|:\*\*)[[:space:]]*($s)" "$f" && n=$((n+1)); done
    echo "- ${s%%|*}: $n" | sed 's/To ?Do/Todo/'
  done
} > "$DIR/INDEX.md"
echo "tasks-index: wrote $DIR/INDEX.md ($count tasks)"
