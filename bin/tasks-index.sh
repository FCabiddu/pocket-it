#!/usr/bin/env bash
# Regenerates tasks/INDEX.md from the task files. Run from the target project root.
# Usage: bash ~/.claude/agents/pocket-it/bin/tasks-index.sh [tasks-dir]
set -euo pipefail
DIR="${1:-tasks}"
[[ -d "$DIR" ]] || { echo "no $DIR/ directory" >&2; exit 1; }

field() { # field <file> <name>  — tolerates **Name**: and **Name:** forms
  grep -m1 -E "^\*\*$2(\*\*:|:\*\*)" "$1" 2>/dev/null | sed -E "s/^\*\*$2(\*\*:|:\*\*)[[:space:]]*//" | sed -E 's/[[:space:]]+$//'
}
title() { head -1 "$1" | sed -E 's/^#[[:space:]]*//'; }

{
  echo "# Task board"
  echo
  echo "Generated by tasks-index.sh — do not edit by hand. Counts: $(ls "$DIR"/*.md 2>/dev/null | grep -v INDEX.md | wc -l | tr -d ' ') tasks."
  echo
  echo "| ID | Title | Label | Status | Depends on | PR |"
  echo "|---|---|---|---|---|---|"
  for f in $(ls "$DIR"/*.md 2>/dev/null | grep -v INDEX.md | sort -V); do
    t=$(title "$f"); id="${t%% —*}"; id="${id%%:*}"; name="${t#*— }"; [[ "$name" == "$t" ]] && name="${t#*: }"
    st=$(field "$f" Status); st="${st:-Todo}"
    lb=$(field "$f" Label); dep=$(field "$f" "Depends on"); [[ -z "$dep" ]] && dep=$(field "$f" "Depends On"); pr=$(field "$f" PR)
    [[ -n "$pr" ]] && pr="[#${pr##*/}]($pr)"
    echo "| $id | $name | ${lb:--} | $st | ${dep:-none} | ${pr:--} |"
  done
  echo
  echo "## Summary"
  for s in Todo "In Progress" "Needs Work" Done; do
    n=$(grep -lE "^\*\*Status(\*\*:|:\*\*)[[:space:]]*$s" "$DIR"/*.md 2>/dev/null | grep -v INDEX.md | wc -l | tr -d ' ')
    echo "- $s: $n"
  done
} > "$DIR/INDEX.md"
echo "wrote $DIR/INDEX.md"
